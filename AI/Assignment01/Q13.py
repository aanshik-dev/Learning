def calculate_rectangle_area(length=1, width=1):
  area = length * width
  return area

print(calculate_rectangle_area(2, 3))
print(calculate_rectangle_area(width=5, length=3))
print(calculate_rectangle_area())

print(calculate_rectangle_area(5))
print(calculate_rectangle_area(width=5))
print(calculate_rectangle_area(length=5))